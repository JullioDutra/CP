import assert from 'node:assert/strict';
import { Room } from '../server/room.js';
import { snapshotRoom, restoreRoom, advanceRoom } from '../server/durable-rooms.js';
import { loadTestDict } from './helpers.mjs';
loadTestDict();
let now = 1000000, records = 0;
const options = { now: () => now, setTimer: () => null, clearTimer: () => {}, seed: 12 };
let room = new Room('TEST', options);
const a = room.addPlayer({ name: 'Ana', avatar: '🦊' });
const b = room.addPlayer({ name: 'Beto', avatar: '🐼' });
room.setOptions(a.id, { rounds: 1, seconds: 60, size: 4 });
room.start(a.id);
const store = { recordMatch: async m => { records++; return { id: 'one', ratings: {}, achievements: {} }; } };
room = restoreRoom(snapshotRoom(room), { now: () => now });
assert.equal(room.phase, 'countdown');
assert.equal(room.resume(a.id, a.token).id, a.id);
assert.equal(room.resume(a.id, 'wrong'), null);
now += 4000;
await advanceRoom(room, store, now);
assert.equal(room.phase, 'playing');
assert.ok(room.rd.possible.length);
assert.ok(room.players.get(a.id).rs.pending instanceof Set);
const clone = restoreRoom(snapshotRoom(room), { now: () => now });
assert.deepEqual(clone.stateFor(b.id), room.stateFor(b.id));
assert.equal(clone.rng.next(), room.rng.next());
now += 61000;
await advanceRoom(clone, store, now);
assert.equal(clone.phase, 'final');
assert.equal(records, 1);
const again = restoreRoom(snapshotRoom(clone), { now: () => now });
await advanceRoom(again, store, now);
assert.equal(records, 1, 'A resumed final must not duplicate the result');
console.log('ok durable rooms: reconnect, deadlines, state and exactly-once result');
